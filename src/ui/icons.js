// Pixel-art icon set for the "rescue dossier x voxel" UI.
//
// Every icon lives on a 16x16 grid and is stored as 16 rows of 16 characters:
//   '#'  fill = `color`
//   'o'  fill = `accent`
//   '+'  fill = `color` at 0.45 opacity (secondary / dim tone)
//   '.'  empty
//   'b' 'l' 'd' 's'  fixed warm browns (sausage only): base / light / dark / stick
// Horizontal runs of the same glyph are merged into one <rect>, and identical
// runs on consecutive rows are merged vertically, to keep the markup small.
//
// An ICONS entry may alternatively be a raw SVG inner-markup string (16x16 viewBox);
// it is used as-is.

