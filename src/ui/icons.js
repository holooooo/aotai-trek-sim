// ---------------------------------------------------------------- compiler

const compiled = new Map(); // name -> [{ x, y, w, h, ch }]

/** ASCII rows -> merged rect list. */
function compileRows(rows) {
  const done = [];
  let open = new Map(); // `${x},${w},${ch}` -> rect still growing downward
  rows.forEach((row, y) => {
    const next = new Map();
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w++;
      if (ch !== '.') {
        const key = `${x},${w},${ch}`;
        const prev = open.get(key);
        if (prev && prev.y + prev.h === y) {
          prev.h++;
          next.set(key, prev);
          open.delete(key);
        } else {
          const r = { x, y, w, h: 1, ch };
          next.set(key, r);
          done.push(r);
        }
      }
      x += w;
    }
    open = next;
  });
  return done;
}

function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function body(name, color, accent) {
  const def = ICONS[name];
  if (typeof def === 'string') return def;
  let rects = compiled.get(name);
  if (!rects) {
    rects = compileRows(def);
    compiled.set(name, rects);
  }
  const c = esc(color);
  const a = esc(accent);
  return rects
    .map(({ x, y, w, h, ch }) => {
      const geo = `x="${x}" y="${y}" width="${w}" height="${h}"`;
      if (ch === '#') return `<rect ${geo} fill="${c}"/>`;
      if (ch === 'o') return `<rect ${geo} fill="${a}"/>`;
      if (ch === '+') return `<rect ${geo} fill="${c}" opacity="0.45"/>`;
      return `<rect ${geo} fill="${FIXED[ch] || c}"/>`;
    })
    .join('');
}

/**
 * Inline SVG string for icon `name`. Unknown names render an empty outlined box.
 */
export function icon(name, { size = 20, color = 'currentColor', accent = '#ff5a1f', cls = '' } = {}) {
  const inner = ICONS[name]
    ? body(name, color, accent)
    : `<rect x="2" y="2" width="12" height="12" fill="none" stroke="${esc(color)}" stroke-width="1" opacity="0.45"/>`;
  return `<svg class="ico ${esc(cls)}" viewBox="0 0 ${GRID} ${GRID}" width="${esc(size)}" height="${esc(size)}" shape-rendering="crispEdges" aria-hidden="true">${inner}</svg>`;
}

